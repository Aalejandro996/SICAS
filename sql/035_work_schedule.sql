-- Segundos hábiles entre dos instantes: solo días laborables de 8:00 a 17:00 (America/Caracas).
CREATE OR REPLACE FUNCTION engagement.business_seconds(t1 TIMESTAMPTZ, t2 TIMESTAMPTZ) RETURNS BIGINT
LANGUAGE sql STABLE AS $$
    SELECT CASE WHEN t1 IS NULL OR t2 IS NULL OR t2 <= t1 THEN 0 ELSE COALESCE((
        SELECT sum(greatest(0, extract(epoch FROM
                   least(t2 AT TIME ZONE 'America/Caracas', g.d + time '17:00')
                 - greatest(t1 AT TIME ZONE 'America/Caracas', g.d + time '08:00'))))::bigint
        FROM (SELECT gs::date AS d FROM generate_series((t1 AT TIME ZONE 'America/Caracas')::date,
                                                        (t2 AT TIME ZONE 'America/Caracas')::date, interval '1 day') AS gs) g
        WHERE extract(isodow FROM g.d) < 6
          AND NOT EXISTS (SELECT 1 FROM admin.holidays h WHERE h.holiday_date = g.d AND h.observed)
    ), 0) END
$$;
GRANT EXECUTE ON FUNCTION engagement.business_seconds(TIMESTAMPTZ, TIMESTAMPTZ) TO app_rw;

-- Horas extras: las solicita el usuario sujeto al horario; las aprueban en orden Jefe de Auditoría
-- (si corresponde), Gerencia y Contralor. Quedan a la vista del Administrador del Sistema.
CREATE TABLE admin.overtime_requests (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id         UUID NOT NULL REFERENCES iam.users(id),
    audit_domain    VARCHAR(12),
    starts_at       TIMESTAMPTZ NOT NULL,
    ends_at         TIMESTAMPTZ NOT NULL,
    reason          TEXT NOT NULL CHECK (length(btrim(reason)) >= 10),
    status          VARCHAR(18) NOT NULL CHECK (status IN ('PENDING_JEFE','PENDING_GERENCIA','PENDING_CONTRALOR',
                                                           'APPROVED','REJECTED','CANCELLED')),
    jefe_by         UUID REFERENCES iam.users(id),  jefe_at TIMESTAMPTZ,
    gerente_by      UUID REFERENCES iam.users(id),  gerente_at TIMESTAMPTZ,
    contralor_by    UUID REFERENCES iam.users(id),  contralor_at TIMESTAMPTZ,
    rejected_by     UUID REFERENCES iam.users(id),  rejected_at TIMESTAMPTZ, reject_note TEXT,
    first_used_at   TIMESTAMPTZ,
    last_used_at    TIMESTAMPTZ,
    created_at      TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (ends_at > starts_at AND ends_at - starts_at <= interval '12 hours'),
    CHECK (jefe_by IS DISTINCT FROM user_id AND gerente_by IS DISTINCT FROM user_id AND contralor_by IS DISTINCT FROM user_id)
);
CREATE INDEX overtime_active ON admin.overtime_requests (user_id, starts_at, ends_at) WHERE status = 'APPROVED';
GRANT SELECT, INSERT, UPDATE ON admin.overtime_requests TO app_rw;

